"""Account-local bootstrap context. Trusted UID assertions, never attestation.

Codex uses observed CODEX_THREAD_ID. Claude/Cursor take their documented hook
context. Hooks must be installed by the account owner; repository hooks do not
expand eligible account scope. Hosted native contexts are not implemented here.
No token or native inference is generated by context parsing.
"""
import hashlib
import json
import os
import re
from .core import BridgeError, fields

UUID = re.compile(r'[a-fA-F0-9]{8}(?:-[a-fA-F0-9]{4}){3}-[a-fA-F0-9]{12}\Z')
# Identical trusted-account and resume validation used by the installed client.
PEERS = frozenset(('mikkel@pop-os', 'work@pop-os'))
OPENCODE_SESSION = re.compile(r'ses_[A-Za-z0-9]{8,124}\Z')
OPENCODE_MESSAGE = re.compile(r'msg_[A-Za-z0-9]{8,124}\Z')
NATIVE = re.compile(r'[A-Za-z0-9][A-Za-z0-9_:-]{7,127}\Z')


def context(client, *, env=None, hook=None):
    env = os.environ if env is None else env
    if env.get('CLAUDE_CODE_REMOTE') == 'true':
        raise BridgeError('Hosted automatic bootstrap is unsupported',403)
    if client == 'codex':
        if hook is not None:
            if not isinstance(hook,dict) or hook.get('hook_event_name')!='SessionStart':
                raise BridgeError('Codex requires its account-local SessionStart context')
            native=hook.get('session_id')
            if env.get('CODEX_THREAD_ID') and env['CODEX_THREAD_ID'].lower()!=str(native).lower():
                raise BridgeError('Codex native hook/environment mismatch')
        else:native = env.get('CODEX_THREAD_ID')
        if not isinstance(native,str) or not UUID.fullmatch(native):
            raise BridgeError('Codex native CODEX_THREAD_ID is unavailable')
        native=native.lower()
        kind,event='bootstrap','bootstrap:'+native
    elif client == 'claude':
        if not isinstance(hook,dict) or hook.get('hook_event_name') != 'SessionStart':
            raise BridgeError('Claude requires its account-local SessionStart context')
        native=hook.get('session_id')
        if not isinstance(native,str) or not UUID.fullmatch(native):
            raise BridgeError('Claude native session ID is unavailable')
        native=native.lower()
        # Startup/reconnect alone is not meaningful activity. Deliberate resume
        # needs fresh runtime evidence, passed separately by the private adapter.
        kind,event='bootstrap','bootstrap:'+native
    elif client == 'grokbot':
        from .grok_lifecycle import event, session
        if not isinstance(hook, dict) or event(hook) != 'SessionStart':
            raise BridgeError('Grok requires its account-local SessionStart context')
        native = session(hook, env=env)
        kind,event='bootstrap','bootstrap:'+native
    elif client == 'opencode':
        if not isinstance(hook,dict) or hook.get('hook_event_name') != 'session.observed':
            raise BridgeError('OpenCode requires its account-local native plugin context')
        native=hook.get('session_id')
        if not isinstance(native,str) or not OPENCODE_SESSION.fullmatch(native):
            raise BridgeError('OpenCode native session ID is unavailable')
        kind,event='bootstrap','bootstrap:'+native
    elif client == 'cursor':
        if not isinstance(hook,dict) or hook.get('hook_event_name') != 'sessionStart':
            raise BridgeError('Cursor requires its account-local sessionStart context')
        native=hook.get('session_id')
        if not isinstance(native,str) or not NATIVE.fullmatch(native):
            raise BridgeError('Cursor native session ID is unavailable')
        if hook.get('conversation_id',native)!=native:
            raise BridgeError('Cursor session/conversation mismatch')
        kind,event='bootstrap','bootstrap:'+hashlib.sha256(native.encode()).hexdigest()
    else:
        raise BridgeError('This native context adapter is not implemented')
    return {'client':client,'native_id':native,'event_id':event,'kind':kind}


def request(client, sha256, *, env=None, hook=None):
    if not isinstance(sha256,str) or not re.fullmatch(r'[a-f0-9]{64}',sha256) or sha256=='0'*64:
        raise BridgeError('A private per-session credential digest is required')
    return {'schema_version':2, **context(client,env=env,hook=hook), 'sha256':sha256}


def local_key(peer, ctx):
    # Stable actual context, not a user-selected task label. Forks get new IDs.
    return hashlib.sha256(json.dumps([peer,ctx['client'],ctx['native_id']],separators=(',',':')).encode()).hexdigest()[:32]
